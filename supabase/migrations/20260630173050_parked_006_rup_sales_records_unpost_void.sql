-- PARKED-006 — codex-driven-bug-hunt cycle 4 (MED, foundation compliance gap).
-- dedupeKey: job-billing-bridge:unpost_invoice:orphan_rup_sales_records
--
-- THE GAP
-- post_invoice → generate_rup_sales_records (live verified 2026-06-30) writes
-- ONE rup_sales_records row per (invoice_id, product_id) for every RUP product
-- on the invoice. The new unpost_invoice (20260625130000) deliberately leaves
-- those rows behind, citing "RUP sales records are an append-only legal/
-- compliance trail (a restricted-use-pesticide sale DID happen at post time);
-- unposting the bill does not unsell the chemical, so we intentionally leave
-- them." (lines 59-61 of the migration).
--
-- That framing is correct when the post was VALID and unpost is a workflow
-- pause — the legal record should persist. But unpost is ALSO documented as
-- the cure for an ACCIDENTAL post ("undo an accidental/early posting on a
-- still-unpaid bill", line 31). The RUP row generated by the accidental post
-- now records a sale that the office is explicitly removing from posted state.
-- A subsequent edit + re-post creates this state:
--   * The dedup in generate_rup_sales_records (`NOT EXISTS … same invoice_id +
--     product_id`) SKIPS the now-stale RUP row.
--   * If the products on the invoice CHANGED between the unpost and the re-
--     post (e.g., a wrong product was removed), the original stale row
--     persists, AND the corrected products get fresh RUP rows.
-- The compliance report (`get_rup_sales_register`, live-verified 2026-06-30 —
-- selects from rup_sales_records with no invoice-status filter) would then
-- show BOTH rows — the corrected sale AND the stale erroneous one — to any
-- auditor or regulator running it.
--
-- WHY MED, NOT HIGH
-- Live state today: 0 rup_sales_records (operationally empty; no compliance
-- corruption possible). HIGH parallels (PARKED-001, PARKED-003) touched the
-- money ledger directly; this touches a regulated audit trail with zero current
-- data. Upgrade to HIGH the moment the first RUP product is sold live.
--
-- THE FIX — append-only with a "voided" marker (regulatory-faithful pattern)
-- "Append-only" doesn't mean "rows must never be hidden from reports"; it
-- means "rows must never be silently deleted". The right pattern is a
-- void_at timestamp + a void reason, and a register report that filters
-- voided rows by default.
--
-- This migration does THREE things:
--   1. ADD 3 columns to rup_sales_records: voided_at timestamptz, voided_by
--      uuid, void_reason text. Nullable; existing rows keep voided_at = NULL.
--   2. Patch unpost_invoice to mark its invoice's RUP rows voided_at = now()
--      with reason 'Invoice unposted' (only the ones with voided_at IS NULL —
--      idempotent). The append-only ledger gains an 'rup_sales_voided' audit
--      row (additive CHECK superset, mirrors invoice_unposted).
--   3. Patch get_rup_sales_register to add `p_include_voided boolean DEFAULT
--      false` and filter voided_at IS NULL when not included. Existing callers
--      (no extra arg) get the current "active sales only" semantics — what
--      they almost certainly already expect.
--   4. (BONUS) Patch generate_rup_sales_records's dedup so a re-post can
--      regenerate a fresh active row even when a stale voided row exists for
--      the same (invoice_id, product_id) — change the NOT EXISTS predicate
--      from "same invoice_id AND product_id" to ALSO require voided_at IS NULL.
--      Without this, a re-post would dedup against the voided row and skip
--      legitimate new sales.
--
-- Every other byte of unpost_invoice / generate_rup_sales_records / get_rup_sales_register
-- is preserved verbatim. Reversible: drop the 3 columns, revert the 3 RPCs.
--
-- PARKED: do NOT apply without Mason's explicit OK.
-- ============================================================================

-- ── 1. Schema: add the void columns to rup_sales_records ─────────────────────
ALTER TABLE public.rup_sales_records
  ADD COLUMN IF NOT EXISTS voided_at  timestamptz NULL,
  ADD COLUMN IF NOT EXISTS voided_by  uuid        NULL REFERENCES public.profiles(id),
  ADD COLUMN IF NOT EXISTS void_reason text       NULL;

-- Helpful filter index (register reads + future-proof: dedup probe is no longer
-- selective enough without it as data accumulates).
CREATE INDEX IF NOT EXISTS idx_rup_sales_records_active
  ON public.rup_sales_records (invoice_id, product_id)
  WHERE voided_at IS NULL;

