#!/usr/bin/env node
// UserPromptSubmit hook for CRX Manager.
// Detects plain-English review/ship/push wording and reminds the agent to route
// through the Codex Review Gauntlet. This does NOT block Mason's prompt — on any
// error it stays silent and exits 0.
//
// Design note: Mason runs a farm-chemical business, so review-ish words ("review",
// "check", "safe", "ready", "ship", "push", "deliver", "merge") collide with everyday
// domain talk ("review the meeting notes", "is the herbicide safe to spray", "ship
// grain", "merge two invoices", "is this load production ready to haul out"). The
// trigger fires only when the OBJECT of the question is the code change itself
// (this/this code/this migration/what claude did/the rpc + "safe") or an unambiguous
// code verb used intransitively (push/merge/deploy/commit with no domain object). A
// DOMAIN negative-lookahead keeps farm/business phrasings silent.
//
// Tuned against one phrasing corpus and validated against two further never-tuned
// corpora (525 phrases total, generated by independent agents): ~100% recall / ~99%+
// precision on those sets. It is a best-effort nudge, not a gate — Claude's own
// judgement and the /codex-gauntlet skill still route obvious cases if the hook misses.
// Regression cases live in codex-gauntlet-reminder.test.mjs.

import { readFileSync } from "node:fs";
import { isMachineGenerated, PUSH_POLICY } from "./prompt-source-lib.mjs";

function emit(extra) {
  if (extra) {
    process.stdout.write(JSON.stringify({
      hookSpecificOutput: { hookEventName: "UserPromptSubmit", additionalContext: extra }
    }));
  }
  process.exit(0);
}

let payload;
try {
  payload = globalThis.__CRX_ROUTED_HOOK_PAYLOAD ?? JSON.parse(readFileSync(0, "utf8"));
} catch {
  emit();
}

// Machine-generated envelopes (<task-notification>, <system-reminder>, slash-command
// output) are not something Mason typed — stay silent so review-ish words inside an
// embedded report can't trip the gauntlet reminder.
if (isMachineGenerated(payload?.prompt)) emit();

const prompt = String(payload?.prompt || "").toLowerCase();
if (!prompt) emit();

// Farm/business objects that mark a NON-code-review question.
const DOMAIN = String.raw`(?:orders?|invoices?|customers?|growers?|inventory|stock|products?|fertiliz\w*|herbicid\w*|roundup|tank|soybeans?|corn|creek|soil|weather|fields?|spray\w*|trucks?|deliver\w*|freight|meetings?|notes?|contracts?|lease|resumes?|taxe?s?|photos?|emails?|suppliers?|vendors?|bills?|blend|tickets?|batch|recipe|surfactant|anhydrous|glyphosate|micronutrient|co-?op|elevator|credit|promo|pricing|seasons?|budget|bins?|warehouse|grain|maths?|samples?|logo|buttons?|fonts?|dashboard|pages?|reports?|columns?|accounts?|balances?|profiles?|statements?|dates?|guys?|staff|applicators?|applicant|hire|chemicals?|booking|tables?|leads?|calendar|quotes?|water|temperature|acres?|access|loads?|spreader|markup|rebate|commissions?|payouts?|payroll|prepay\w*|books)`;
const NOT_DOMAIN = String.raw`(?!\s+(?:\w+\s+){0,2}` + DOMAIN + String.raw`)`;

const triggerPatterns = [
  // 1. Unambiguous code anchors / code-target phrases (verified absent from all decoy corpora).
  /\b(preflight|gauntlet|lgtm)\b/,
  /\bcodex\b/,
  /\breviewers?\b/,
  /\bcroprxsolutions\b/,
  /\b(?:the|this)\s+code\b/,
  /\b(?:this|the)\s+migration\b/,
  /\bthis\s+change\b/,
  /\bthese\s+changes\b/,
  /\bcode\s+change\b/,
  /\bthis\s+deploy\b/,
  /\bdeploy\s+(?:this|it)\b/,
  /\brefactor\w*\b/,
  /\bsql\b/,
  /\bdatabase\b/,
  /\bthe\s+db\b/,
  /\bdb\s+change\b/,
  /\bedge\s+f(?:unction|n)\b/,
  /\b(?:the|this)\s+branch\b/,
  /\b(?:to|onto)\s+main\b/,
  /\blive\s+(?:site|app|database|db)\b/,
  /\b(?:to|for|in|hits?|hit)\s+production\b/,
  /\b(?:shippable|deployable|pushable)\b/,
  /\bmergeable\b(?!\s+into\b)/,
  /\bwhat\s+(?:we|you|u|i)\s+(?:just\s+)?(?:built|changed|change|wrote|coded|did|made|added|fixed|created)\b/,
  /\b(?:you|u|we|i|claude)\s+(?:just\s+)?(?:built|wrote|coded|made|created)\b/,

  // 2. "claude" tied to work/review wording (also matches a curly apostrophe in claude's).
  /\bclaude['’]?s?\b[^.?!]*\b(work|code|change|did|wrote|writing|review|check|break|safe|ship|merge|push|deploy|once|eyeball|vet|sure)/,
  /\b(work|code|change|did|wrote|review|check|break|safe|ship|merge|push|deploy|once|eyeball|vet)\b[^.?!]*\bclaude/,

  // 3. ship/push/merge/deploy/commit — code target + clause-terminal, never a domain object.
  /\b(?:ship|push|merge|deploy|commit)\b(?:\s+(?:this|it|these|that))?(?:\s+(?:up|in|out))?\s*(?:to\s+(?:prod\w*|main|live))?\s*(?:[?.!]|$|\b(?:before|now|yet|pls|please|or\s+not)\b)/,
  new RegExp(
    String.raw`\b(?:before|after)\s+(?:i|we|you|it|this|they)?\s*(?:push|merg|ship|deploy|commit|appl|releas|going?\s*live|hit)\w*\b` +
    String.raw`(?!\s+(?:the\s+|a\s+|an\s+)?(?:\w+\s+){0,1}` + DOMAIN + String.raw`)`,
    ""
  ),
  /\brun\s+it\s+past\b/,
  /\bworried\s+about\s+(?:push|ship|deploy|merg|going\s+live|releas)\w*/,

  // 4. safe/ok/ready/good/clear + to + CODE verb, clause-terminal (guards "ready to ship grain").
  /\b(?:safe|ok|okay|ready|good|clear|alright|cleared|fine)\b[^.?!]{0,20}?\bto\s+(?:ship|push|merge|deploy|commit|go\s*live|put\s*(?:it\s*)?live|release)\b(?:\s+(?:this|it|up|in))?(?:\s+to\s+(?:prod\w*|main|live))?\s*(?:[?.!]|$|\b(?:before|now|yet|pls|please|or\s+not)\b)/,
  /\b(?:this|it|everything|we|that)\s+(?:is\s+|are\s+)?good\s+to\s+go\b/,
  // Domain guard: do NOT fire on "is this delivery/load/order good to go?" — only on
  // a deploy-flavored "good to go" that is NOT preceded by a farm/business object.
  new RegExp(
    String.raw`(?<!\b` + DOMAIN + String.raw`\s)` +
    String.raw`\bgood\s+to\s+go\b(?:\s*[?.!]|\s+(?:live|to\s+prod\w*|to\s+production|with\s+(?:this|the)|on\s+this|or\s+(?:not|no)|before|yet|now))`,
    ""
  ),
  /\b(?:ready|safe|ok|okay|clear|alright)\s+to\s+go\s+live\b/,
  /\bis\s+(?:it|this)\s+(?:gonna\s+be\s+)?ready\s+to\s+go\b/,
  /\bgo(?:es|ing)?\s+live\b/,
  /\bgo(?:es)?\s+to\s+(?:prod\w*|production|the\s+live|customers)\b/,
  /\b(?:this|it)\s+go(?:es|ing)?\s+live\b/,
  /\bthis\s+go(?:es|ing)?\s+out\b/,
  /\bsend\s+(?:it|this)\s+live\b/,
  /\bgoes\s+to\s+(?:the\s+live|customers|prod)/,
  /\bhits?\s+(?:prod\w*|customers|the\s+(?:live|real))\b/,
  /\bput\s+(?:it|this)\s+(?:live|out)\b/,
  /\bput\s+(?:it|this)\s+on\s+the\s+(?:real\s+|live\s+)?site\b/,
  /\benough\s+to\s+(?:ship|push|merge|deploy|go\b|go\s+live|go\s+out|put\s+(?:it|this|out)|release)/,
  /\b(?:ready|safe)\s+for\s+prod\w*/,
  new RegExp(
    String.raw`\bare\s+we\s+(?:good|ok|okay|ready|safe|clear|cleared)\s+(?:here\b|[?.!]|$|to\s+(?:ship|push|merge|deploy|commit|go\b)` +
    String.raw`(?!\s+(?:the\s+|a\s+)?(?:\w+\s+){0,1}` + DOMAIN + String.raw`))`,
    ""
  ),
  // a code routine named near a review/ready adjective ("commission rpc safe") — but not a build request.
  /\b(?:rpc|sql|migration|function|edge\s*fn|query|trigger)\b[^.?!]{0,15}?\b(?:safe|ready|reviewed|correct|shippable|solid|good\s+to\s+(?:go|ship|merge|push|deploy)|ok\s+to\s+(?:ship|push|merge|deploy))\b/,
  /\b(?:safe|reviewed|shippable|good\s+to\s+go|ready\s+to\s+(?:ship|push|merge|deploy))\b[^.?!]{0,15}?\b(?:rpc|sql|migration|edge\s*function)\b/,

  // 5. intent verb + deictic (this/these, NOT bare back-referential "it") not followed by a domain noun,
  //    or + explicit code target, or + "before i push", plus look/once-over / second-opinion forms.
  new RegExp(
    String.raw`\b(?:check|recheck|review|reviewed|reviewing|double[-\s]?check|doublecheck|duble\s*check|sanity[-\s]?check|gut[-\s]?check|cross[-\s]?check|eyeball|vet|verify)\b` +
    String.raw`(?:\s+(?:and|please|pls|real\s*quick|over|nothing))*` +
    String.raw`\s+(?:this|these)\b` + NOT_DOMAIN,
    ""
  ),
  /\b(?:check|recheck|review|reviewed|reviewing|double[-\s]?check|doublecheck|sanity[-\s]?check|gut[-\s]?check|cross[-\s]?check|eyeball|vet|verify|look\s+over|go\s+over)\b[^.?!]{0,20}?\b(?:the\s+(?:\w+\s+){0,2}(?:code|function|rpc|sql|query|migration|edge\s*fn)|this\s+code|this\s+change|these\s+changes|this\s+migration|the\s+migration|your\s+work|what\s+(?:you|claude))/,
  new RegExp(
    String.raw`\b(?:check|review|double[-\s]?check|sanity[-\s]?check|gut[-\s]?check|eyeball|vet|verify|look|go)\b[^.?!]{0,40}?\bbefore\s+(?:i|we|you)?\s*(?:push|merg|ship|deploy|commit|appl)\w*\b` +
    String.raw`(?!\s+(?:the\s+|a\s+|an\s+)?(?:\w+\s+){0,1}` + DOMAIN + String.raw`)`,
    ""
  ),
  /\b(?:looked|checked)\s+over\b/,
  new RegExp(String.raw`\b(?:look|go)\s+(?:this|these)\s+over\b` + NOT_DOMAIN, ""),
  new RegExp(String.raw`\b(?:look|go)\s+over\s+(?:this|these|what|claude|your|my\s+code|the\s+code|the\s+migration|the\s+change)\b` + NOT_DOMAIN, ""),
  /\bgive\s+(?:it|this|the\s+code|the\s+changes?|claude['’]?s?[^.?!]*?)\s+(?:a\s+|the\s+|another\s+)?(?:once[-\s]?over|look|review|second\s+(?:look|opinion))\b/,
  new RegExp(
    String.raw`\bsecond\s+(?:opinion|set\s+of\s+eyes|eyes|pair\s+of\s+eyes)\b[^.?!]{0,25}?\b(?:on\s+)?` +
    String.raw`(?:this\s+(?:change|code|migration|fix|edit|pr)|the\s+(?:code|change|migration)|claude|` +
    String.raw`before\s+(?:i|we)\s+(?:push|merg|ship|deploy|commit)\w*|this\b` + NOT_DOMAIN + String.raw`)`,
    ""
  ),

  // 6. break / mess up / blow up — code subject or code object only.
  /\bdid\s+(?:you|u|claude)\s+(?:just\s+)?(?:break|introduce|mess\s*up|screw\s*up|blow\s*up)\b/,
  /\b(?:break|broke|broken|mess\w*\s*up|blew?\s*up|nuke[ds]?)\b[^.?!]{0,20}?\b(?:prod\w*|the\s+(?:live|app|site|database|db)|billing|payment\w*|invoic\w*|something\s+when)\b/,
  /\b(?:this|it|that|the\s+(?:change|migration|fix|edit|code|patch|function|rpc|app)|my\s+(?:change|migration|fix|edit|code))\s+\w*\s*(?:gonna\s+|is\s+gonna\s+|going\s+to\s+|to\s+|might\s+|will\s+|wont\s+|won['’]?t\s+|did\s*n['’]?t\s+|does\s*n['’]?t\s+)?(?:break|blow\s*up|mess\w*\s*up)\b/,
  /\banything\s+(?:gonna|gunna|going\s+to|might|could|will)\s+(?:break|blow)\b/,
  /\bblow\s+(?:anything|something|it|stuff|the\s+\w+)\s+up\b/,
  /\bcould\s+(?:this|it)\s+break\b/,
  /\bnothing\s+(?:is\s+)?broke?(?:n)?\b/,
  /\bmake\s+sure\s+\w+\s+(?:did\s*n['’]?t|wont|won['’]?t)\s+break\b/,
  /\b(?:corrupt|nuke|wreck)\s+(?:anything|the\s+(?:db|database|data|live))/,
  /\bbefore\s+i\s+push\s+the\s+migration\b/,

  // 7. "is this/it safe|ready|clean|solid|correct|risky|shippable" — deictic THIS/IT only,
  //    NOT "is it safe to spray/drive/deliver/...".
  /\bis\s+(?:this|it)\s+(?:change\s+|code\s+|thing\s+|fix\s+|actually\s+)?(?:safe|ready|clean|solid|correct|risky|reviewed|shippable|pushable|mergeable|deployable|working\s+right)\b(?!\s+to\s+(?:spray|drive|give|tank[-\s]?mix|mix|apply|extend|use|put|feed|load|store|haul|transport|handle|operate|deliver|sell|fill|plant|reuse|keep))/,
  /\bis\s+(?:this|it)\s+(?:change\s+|thing\s+)?(?:production[-\s]?ready|good\s+to\s+go|ready\s+for\s+prod\w*|safe\s+to\s+(?:ship|push|merge|deploy|go|put))/,
  /\b(?:this|it)\s+(?:safe|shippable)\s*[?.!]?\s*$/,
  /^\s*(?:is\s+)?this\s+good\s*\?/,
  new RegExp(
    String.raw`\bis\s+everything\s+(?:good\s+to\s+go|ok|okay|safe|ready|green)\b` +
    String.raw`(?!\s+(?:with\s+|on\s+|about\s+)?(?:the\s+|these\s+|those\s+|this\s+)?(?:\w+\s+){0,1}` + DOMAIN + String.raw`)`,
    ""
  ),
  /\bis\s+this\s+done\s+and\s+ready\b/,
  /\bis\s+this\s+(?:ready|reviewed)\b/,
  /\bis\s+it\s+ready\s+to\s+(?:commit|go\s+out|ship|push|deploy|merge)\b/,
  /\bis\s+(?:my|the)\s+(?:app|code|migration|fix|edit|change|function|rpc|sql)\s+(?:change\s+)?(?:safe|ready|shippable|correct|clean|solid|good)\b/,
  /\b(?:my|the)\s+(?:app\s+change|code|migration|fix|hotfix|edit|patch|new\s+function|new\s+rpc)\b[^.?!]{0,30}?\b(?:safe|ready|shippable|correct|solid|reviewed|good\s+to\s+(?:ship|merge|go|push|deploy))\b/,
  /\bgreen\s+to\s+(?:go|push|ship|deploy|merge)\b/,
  /\bis\s+(?:everything|the\s+code|this)\s+green\b/,

  // 8. "any bugs / any risk / anything wrong|sketchy|landmines" (domain-guarded) and "any issues|problems + code".
  /\bany\s+bugs?\b/,
  /\bany\s+risk\b/,
  /\bany\s+landmines?\b/,
  new RegExp(String.raw`\banything\s+(?:wrong|sketchy|off|broken|new)\b` + NOT_DOMAIN, ""),
  /\banything\s+(?:i\s+should\s+worry|that\s+could\s+go\s+wrong)\b/,
  /\bany\s+(?:issues?|problems?)\b[^.?!]{0,15}?\b(?:code|change|migration|build|the\s+app)\b/,

  // 9. terse reverse forms: "this been reviewed", "u/you sure this ...", "did this come out right".
  /\b(?:this|it|these|everything)\s+(?:has\s+)?(?:been\s+)?(?:reviewed|vetted|verified|double[-\s]?checked)\b/,
  /\b(?:be|been)\s+reviewed\b/,
  /\b(?:u|you|ya)\s+(?:sure|think|positive|certain)\b[^.?!]{0,25}?\b(?:this|it)\b/,
  /\b(?:did|does)\s+(?:this|it|that\s+thing|my\s+\w+)?\s*(?:come|came)\s+out\s+\w+/,
  /\bcome\s+out\s+(?:right|ok|okay|correct|fine)\b/,
];

if (!triggerPatterns.some((pattern) => pattern.test(prompt))) emit();

emit([
  "CRX Codex Review Gauntlet reminder:",
  "",
  "Mason has zero coding experience and should not need to remember command names.",
  "If this prompt is asking whether work is safe, ready, reviewed, shippable, pushable, mergeable, or deployable, route it through the Codex Review Gauntlet automatically.",
  "",
  "Default path:",
  "- Use per-change mode for current branch, commit, staged, unstaged, or untracked work.",
  "- Use foundation audit mode only when Mason asks for a broad app/workflow safety review.",
  "- If the mode or scope is unclear, ask one short question.",
  "",
  PUSH_POLICY,
  "",
  "Source of truth: C:\\CRX_Manager\\.claude\\commands\\codex-gauntlet.md"
].join("\n"));
